"""표의 모든 행 뽑기 (`from: table_rows`).

지금 어휘는 **칸 하나**만 집는다(`labels` 로 라벨을 찾고 그 옆/아래). 그런데 값이
칸 하나가 아니라 표 전체인 항목이 여럿 막혀 있다:

    EV2 개정기록 완전성      개정번호·일시·해당 절·개정 사유·담당자·승인자 × 9행
    EV2 평가표 완전성        빈 셀·미판정 행 찾기
    AI시험인증1 1-18         제출물 목록 ↔ 제출물명 대조
    AI시험인증1 1-4·1-11     시험절차·장비 목록

머리행의 **열 이름들로 표를 찾고**, 그 아래 행을 낸다. 라벨 하나로 찾는 것과 다르다 —
표를 특정하려면 열 조합이 있어야 한다("담당자" 만으로는 어느 표인지 모른다).
"""
from modules.doc_parser import FieldSpec, RawDoc, extract_fields, normalize


def _doc(*lines):
    return normalize(RawDoc(source_path="t.docx", text="\n".join(lines)))


def _rows(doc, **kw):
    kw.setdefault("name", "개정기록")
    kw.setdefault("source", "table_rows")
    return extract_fields(doc, [FieldSpec(**kw)])[kw["name"]]


# ── 표 찾기 ──────────────────────────────────────────────────────────────

def test_머리행_아래_행들을_낸다():
    doc = _doc("| 개정번호 | 일시 | 개정 사유 |",
               "| 00 | 2021. 06. 21. | 신규 발행 |",
               "| 01 | 2022. 12. 19. | 전면 개정 |")

    got = _rows(doc, columns=("개정번호", "일시", "개정 사유"))

    assert got.found is True
    assert [r.cells for r in got.rows] == [
        {"개정번호": "00", "일시": "2021. 06. 21.", "개정 사유": "신규 발행"},
        {"개정번호": "01", "일시": "2022. 12. 19.", "개정 사유": "전면 개정"}]


def test_사이_빈_열이_있어도_열_이름으로_맞춘다():
    """실측(EV2 RVVR 개정기록): 열 사이에 빈 칸이 하나씩 끼어 있다.

        | 개정번호 |  | 일시 |  | 해당 절 |  | 개정 사유 |  | 담당자 |  | 승인자 |
        | 00      |  | ’21.06.21 |  | 문서 전체 |  | 신규 발행 |  | 정연석 |  | 구자철 |
    """
    doc = _doc("| 개정번호 |  | 일시 |  | 개정 사유 |  | 담당자 |",
               "| 00 |  | ’21.06.21 |  | 신규 발행 |  | 정연석 |")

    got = _rows(doc, columns=("개정번호", "일시", "개정 사유", "담당자"))

    assert got.rows[0].cells == {"개정번호": "00", "일시": "’21.06.21",
                                 "개정 사유": "신규 발행", "담당자": "정연석"}


def test_열_이름은_공백을_무시해_맞춘다():
    doc = _doc("| 개정 번호 | 일 시 |", "| 00 | 2021. 06. 21. |")

    got = _rows(doc, columns=("개정번호", "일시"))

    assert got.rows[0].cells == {"개정번호": "00", "일시": "2021. 06. 21."}


def test_열이_하나라도_없으면_못_찾은_것이다():
    """열 조합으로 표를 특정한다. 일부만 맞으면 다른 표일 수 있다 — 엉뚱한 표를
    검사하면 거짓 지적이 난다."""
    doc = _doc("| 개정번호 | 일시 |", "| 00 | 2021. 06. 21. |")

    got = _rows(doc, columns=("개정번호", "일시", "승인자"))

    assert got.found is False
    assert got.rows == ()


def test_표가_없으면_못_찾은_것이다():
    got = _rows(_doc("본문만 있다"), columns=("개정번호", "일시"))

    assert got.found is False


# ── 어느 행이 진짜 행인가 ────────────────────────────────────────────────

def test_key_열이_빈_행은_빈_양식_행이라_뺀다():
    """실측(제출물 확인증): 실제 제출물은 1건인데 빈 행이 20줄 더 있다.
    그대로 세면 완전성 검사가 20건을 지적한다."""
    doc = _doc("| 제출물명 | 부수 | 확인 |",
               "| 시험접수문서_apple_0101 | 1 | (서명) |",
               "|  |  | (서명) |",
               "|  |  | (서명) |")

    got = _rows(doc, name="제출물목록", columns=("제출물명", "부수", "확인"))

    assert [r.cells["제출물명"] for r in got.rows] == ["시험접수문서_apple_0101"]


def test_key_열을_지정할_수_있다():
    doc = _doc("| 순번 | 제출물명 |",
               "| 1 |  |",
               "| 2 | 설계서 |")

    got = _rows(doc, name="제출물목록", columns=("순번", "제출물명"), key="제출물명")

    assert [r.cells["순번"] for r in got.rows] == ["2"]


def test_머리행보다_칸이_적은_행은_뺀다():
    """실측(제출물 확인증): 표 끝에 `| 비고 |  |` 가 붙는다. 열 수가 안 맞으므로
    이 표의 데이터 행이 아니다 — 그냥 두면 '비고'가 제출물명이 된다."""
    doc = _doc("| 제출물명 | 부수 | 확인 |",
               "| 설계서 | 1 | (서명) |",
               "| 비고 |  |")

    got = _rows(doc, name="제출물목록", columns=("제출물명", "부수", "확인"))

    assert [r.cells["제출물명"] for r in got.rows] == ["설계서"]


def test_되풀이된_머리행은_건너뛴다():
    """표가 쪽을 넘기면 머리행이 다시 나온다. 그대로 두면 '개정번호'가 값이 된다."""
    doc = _doc("| 개정번호 | 일시 |",
               "| 00 | 2021. 06. 21. |",
               "| 개정번호 | 일시 |",
               "| 01 | 2022. 12. 19. |")

    got = _rows(doc, columns=("개정번호", "일시"))

    assert [r.cells["개정번호"] for r in got.rows] == ["00", "01"]


# ── 지적 위치 ────────────────────────────────────────────────────────────

def test_행마다_위치가_붙는다():
    """리포트가 "3행의 담당자가 비었다"를 말하려면 행마다 위치가 있어야 한다."""
    doc = _doc("| 머리 |",
               "| 개정번호 | 일시 |",
               "| 00 | 2021. 06. 21. |",
               "| 01 | 2022. 12. 19. |")

    got = _rows(doc, columns=("개정번호", "일시"))

    assert [r.anchor.section for r in got.rows] == ["표1 3행", "표1 4행"]
    assert got.anchor.section == "표1 2행"        # 머리행 자리


def test_표를_찾으면_행이_없어도_찾은_것이다():
    """머리행만 있고 값이 한 줄도 없는 표 — "표가 없다"와 "표가 비었다"는 다르다.
    전자는 필드맵이 어긋난 것이고 후자는 문서 결함이다."""
    doc = _doc("| 개정번호 | 일시 |")

    got = _rows(doc, columns=("개정번호", "일시"))

    assert got.found is True
    assert got.rows == ()
